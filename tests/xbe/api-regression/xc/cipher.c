/* PLAIN through CBC with an all-zero feedback, both ciphers. */
static const unsigned char DES_CBC[16] = {
    0x32,0x60,0x26,0x6c,0x2c,0xf2,0x02,0xe2,0x79,0xcf,0x70,0xcd,
    0x1d,0xac,0x09,0xa5,
};

static const unsigned char DES3_CBC[16] = {
    0x30,0x32,0x92,0x53,0xbd,0x29,0x65,0x40,0x72,0xa1,0xc2,0x7a,
    0x3b,0x48,0x3e,0xbc,
};

static bool bytes_eq(const unsigned char *got, const unsigned char *want,
                     unsigned n, const char *tag)
{
    unsigned i;
    for (i = 0; i < n; i++) {
        if (got[i] != want[i]) {
            test_record_failure(__FILE__, __LINE__,
                "%s: byte %u got 0x%02x expected 0x%02x",
                tag, i, got[i], want[i]);
            return false;
        }
    }
    return true;
}

static void schedule(ULONG cipher, const unsigned char *key)
{
    memset(g_table, GUARD, sizeof(g_table));
    XcKeyTable(cipher, g_table, (PUCHAR)key);
}

static bool guarded_from(unsigned offset)
{
    unsigned i;
    for (i = offset; i < sizeof(g_table); i++) {
        if (g_table[i] != GUARD)
            FAIL_AND_RETURN("key table wrote +%u, past its %u bytes",
                            i, offset);
    }
    return true;
}

/* The schedule the console publishes, byte for byte. */
static bool t_des_table(void)
{
    schedule(0, KEY);
    return bytes_eq(g_table, DES_TABLE, DES_TABLE_BYTES, "des table");
}

/* DES fills 128 bytes and stops there. */
static bool t_des_table_extent(void)
{
    schedule(0, KEY);
    return guarded_from(DES_TABLE_BYTES);
}

/* Triple-DES is the three keys' schedules, in key order. */
static bool t_des3_table(void)
{
    schedule(1, KEY3);
    if (!bytes_eq(g_table, DES3_TABLE, DES3_TABLE_BYTES, "3des table"))
        return false;
    if (!bytes_eq(g_table, DES_TABLE, DES_TABLE_BYTES, "3des first key"))
        return false;
    return guarded_from(DES3_TABLE_BYTES);
}

/* The cipher number is not an index: anything but zero is triple. */
static bool t_nonzero_cipher_is_triple(void)
{
    schedule(2, KEY3);
    if (!bytes_eq(g_table, DES3_TABLE, DES3_TABLE_BYTES, "cipher 2"))
        return false;
    if (!guarded_from(DES3_TABLE_BYTES))
        return false;

    schedule(0x100, KEY3);
    if (!bytes_eq(g_table, DES3_TABLE, DES3_TABLE_BYTES, "cipher 0x100"))
        return false;
    return guarded_from(DES3_TABLE_BYTES);
}

static bool t_cbc_encrypt(void)
{
    unsigned char out[16], feedback[8];

    schedule(0, KEY);
    memset(out, 0xEE, sizeof(out));
    memset(feedback, 0, sizeof(feedback));
    XcBlockCryptCBC(0, sizeof(out), out, (PUCHAR)PLAIN, g_table, 1, feedback);
    if (!bytes_eq(out, DES_CBC, sizeof(out), "cbc"))
        return false;
    /* The feedback buffer leaves holding the last ciphertext block. */
    return bytes_eq(feedback, DES_CBC + 8, 8, "cbc feedback");
}

static bool t_cbc_decrypt(void)
{
    unsigned char out[16], feedback[8];

    schedule(0, KEY);
    memset(out, 0xEE, sizeof(out));
    memset(feedback, 0, sizeof(feedback));
    XcBlockCryptCBC(0, sizeof(out), out, (PUCHAR)DES_CBC, g_table, 0, feedback);
    if (!bytes_eq(out, PLAIN, sizeof(out), "cbc back"))
        return false;
    return bytes_eq(feedback, DES_CBC + 8, 8, "cbc feedback (decrypt)");
}

/* The caller's feedback carries a run across calls. */
static bool t_cbc_chains(void)
{
    unsigned char out[16], feedback[8];

    schedule(0, KEY);
    memset(out, 0xEE, sizeof(out));
    memset(feedback, 0, sizeof(feedback));
    XcBlockCryptCBC(0, 8, out, (PUCHAR)PLAIN, g_table, 1, feedback);
    XcBlockCryptCBC(0, 8, out + 8, (PUCHAR)PLAIN + 8, g_table, 1, feedback);
    return bytes_eq(out, DES_CBC, sizeof(out), "cbc in two calls");
}

/* A run with no whole block in it touches nothing at all. */
static bool t_cbc_empty(void)
{
    unsigned char out[16], feedback[8];

    schedule(0, KEY);
    memset(out, 0xEE, sizeof(out));
    memset(feedback, 0x55, sizeof(feedback));
    XcBlockCryptCBC(0, 0, out, (PUCHAR)PLAIN, g_table, 1, feedback);
    ASSERT_EQ_U32(out[0], 0xEE);
    ASSERT_EQ_U32(feedback[0], 0x55);
    return true;
}

static bool t_des3_cbc(void)
{
    unsigned char out[16], back[16], feedback[8];

    schedule(1, KEY3);
    memset(out, 0xEE, sizeof(out));
    memset(feedback, 0, sizeof(feedback));
    XcBlockCryptCBC(1, sizeof(out), out, (PUCHAR)PLAIN, g_table, 1, feedback);
    if (!bytes_eq(out, DES3_CBC, sizeof(out), "3des cbc"))
        return false;

    memset(back, 0xEE, sizeof(back));
    memset(feedback, 0, sizeof(feedback));
    XcBlockCryptCBC(1, sizeof(back), back, out, g_table, 0, feedback);
    return bytes_eq(back, PLAIN, sizeof(back), "3des cbc back");
}

/* Encrypting over the input buffer works. */
static bool t_cbc_in_place(void)
{
    unsigned char buf[16], feedback[8];

    schedule(0, KEY);
    memcpy(buf, PLAIN, sizeof(buf));
    memset(feedback, 0, sizeof(feedback));
    XcBlockCryptCBC(0, sizeof(buf), buf, buf, g_table, 1, feedback);
    if (!bytes_eq(buf, DES_CBC, sizeof(buf), "cbc in place"))
        return false;

    memset(feedback, 0, sizeof(feedback));
    XcBlockCryptCBC(0, sizeof(buf), buf, buf, g_table, 0, feedback);
    return bytes_eq(buf, PLAIN, sizeof(buf), "cbc in place back");
}

/* The FIPS single-block vector, straight through the cipher. */
static bool t_block_ecb(void)
{
    static const unsigned char plain[8] = {
        0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xe7};
    static const unsigned char cipher[8] = {
        0xc9, 0x57, 0x44, 0x25, 0x6a, 0x5e, 0xd3, 0x1d};
    unsigned char out[16], back[8];

    schedule(0, KEY);
    memset(out, 0xEE, sizeof(out));
    XcBlockCrypt(0, out, (PUCHAR)plain, g_table, 1);
    if (!bytes_eq(out, cipher, sizeof(cipher), "ecb"))
        return false;
    /* One block, and nothing past it. */
    ASSERT_EQ_U32(out[8], 0xEE);

    XcBlockCrypt(0, back, (PUCHAR)cipher, g_table, 0);
    return bytes_eq(back, plain, sizeof(plain), "ecb back");
}

/* Only operation zero decrypts; every other code encrypts. */
static bool t_block_op_codes(void)
{
    unsigned char out[8];

    schedule(0, KEY);
    XcBlockCrypt(0, out, (PUCHAR)PLAIN, g_table, 2);
    return bytes_eq(out, DES_CBC, sizeof(out), "op 2");
}

/* Triple-DES runs the three schedules encrypt-decrypt-encrypt. */
static bool t_block_triple(void)
{
    unsigned char out[8], back[8];

    schedule(1, KEY3);
    XcBlockCrypt(1, out, (PUCHAR)PLAIN, g_table, 1);
    if (!bytes_eq(out, DES3_CBC, sizeof(out), "3des ecb"))
        return false;

    XcBlockCrypt(1, back, out, g_table, 0);
    return bytes_eq(back, PLAIN, sizeof(back), "3des ecb back");
}

/* The framework's service entry answers zero, whatever it is asked. */
static bool t_crypt_service(void)
{
    ULONG args[8];
    ULONG op;

    memset(args, 0, sizeof(args));
    for (op = 0; op < 16; op++)
        ASSERT_EQ_U32(XcCryptService(op, args), 0);
    return true;
}

