#define MODULUS_BYTES 256
#define MODULUS_WORDS (MODULUS_BYTES / 4)
#define BLOB_MODULUS  20        /* modulus offset inside the blob */

static ULONG g_a[MODULUS_WORDS], g_b[MODULUS_WORDS];
static ULONG g_c[MODULUS_WORDS], g_d[MODULUS_WORDS];

static void set_small(ULONG base, ULONG exponent, ULONG modulus)
{
    memset(g_a, 0, sizeof(g_a));
    memset(g_b, 0, sizeof(g_b));
    memset(g_c, 0, sizeof(g_c));
    memset(g_d, 0, sizeof(g_d));
    g_b[0] = base;
    g_c[0] = exponent;
    g_d[0] = modulus;
}

static bool t_modexp_small(void)
{
    /* 5^3 == 125 == 9*13 + 8 */
    set_small(5, 3, 13);
    ULONG r = XcModExp(g_a, g_b, g_c, g_d, MODULUS_WORDS);
    ASSERT_EQ_U32(r, 1);
    ASSERT_EQ_U32(g_a[0], 8);
    ASSERT_EQ_U32(g_a[1], 0);
    return true;
}

static bool t_modexp_reduces_base(void)
{
    /* A base above the modulus is reduced first: 100^3 mod 13 == 1. */
    set_small(100, 3, 13);
    ULONG r = XcModExp(g_a, g_b, g_c, g_d, MODULUS_WORDS);
    ASSERT_EQ_U32(r, 1);
    ASSERT_EQ_U32(g_a[0], 1);
    return true;
}

static bool t_modexp_even_modulus(void)
{
    /* 7^5 == 16807 == 168*100 + 7.  An even modulus is the one case with
     * no odd-modulus shortcut available. */
    set_small(7, 5, 100);
    ULONG r = XcModExp(g_a, g_b, g_c, g_d, MODULUS_WORDS);
    ASSERT_EQ_U32(r, 1);
    ASSERT_EQ_U32(g_a[0], 7);
    return true;
}

static bool t_modexp_identities(void)
{
    /* Anything to the zeroth power is one; zero to any power is zero. */
    set_small(7, 0, 13);
    ULONG r = XcModExp(g_a, g_b, g_c, g_d, MODULUS_WORDS);
    ASSERT_EQ_U32(r, 1);
    ASSERT_EQ_U32(g_a[0], 1);

    set_small(0, 5, 13);
    r = XcModExp(g_a, g_b, g_c, g_d, MODULUS_WORDS);
    ASSERT_EQ_U32(r, 1);
    ASSERT_EQ_U32(g_a[0], 0);
    return true;
}

/*
 * Raising the signature to the public exponent must reproduce the PKCS#1
 * block the signer padded: the digest reversed at the bottom, then the
 * SHA-1 DigestInfo, a separating zero, 0xff padding, and 0x01 0x00 on top.
 */
static bool t_modexp_rsa_block(void)
{
    static const UCHAR PREFIX[15] = {
        0x14, 0x04, 0x00, 0x05, 0x1a, 0x02, 0x03, 0x0e,
        0x2b, 0x05, 0x06, 0x09, 0x30, 0x21, 0x30,
    };

    memset(g_a, 0, sizeof(g_a));
    memset(g_c, 0, sizeof(g_c));
    memcpy(g_b, SIGNATURE, sizeof(g_b));
    memcpy(g_d, PUBKEY + BLOB_MODULUS, sizeof(g_d));
    g_c[0] = 65537;

    ULONG r = XcModExp(g_a, g_b, g_c, g_d, MODULUS_WORDS);
    ASSERT_EQ_U32(r, 1);

    const UCHAR *blk = (const UCHAR *)g_a;
    for (int i = 0; i < 20; i++)
        if (blk[i] != DIGEST[19 - i])
            FAIL_AND_RETURN("digest byte %d: got 0x%02x expected 0x%02x",
                            i, blk[i], DIGEST[19 - i]);
    if (memcmp(blk + 20, PREFIX, sizeof(PREFIX)) != 0)
        FAIL_AND_RETURN("DigestInfo prefix mismatch");
    ASSERT_EQ_U32(blk[35], 0x00);
    ASSERT_EQ_U32(blk[MODULUS_BYTES - 1], 0x00);
    ASSERT_EQ_U32(blk[MODULUS_BYTES - 2], 0x01);
    for (int i = 36; i < MODULUS_BYTES - 2; i++)
        if (blk[i] != 0xff)
            FAIL_AND_RETURN("padding byte %d is 0x%02x", i, blk[i]);
    return true;
}

static bool t_keylen(void)
{
    /* The ordinal hands back the blob's own length field untouched. */
    ASSERT_EQ_U32(XcPKGetKeyLen((PUCHAR)PUBKEY), 264);
    ASSERT_EQ_U32(XcPKGetKeyLen((PUCHAR)PUBKEY_1K), 136);
    return true;
}

static bool t_keylen_is_not_derived(void)
{
    /* Neither the magic nor the other header fields are consulted. */
    static UCHAR alt[sizeof(PUBKEY)];

    memcpy(alt, PUBKEY, sizeof(alt));
    alt[4] = 0x99; alt[5] = 0x09; alt[6] = 0x00; alt[7] = 0x00;
    ASSERT_EQ_U32(XcPKGetKeyLen(alt), 0x999);

    memcpy(alt, PUBKEY, sizeof(alt));
    alt[0] = 'X';
    ASSERT_EQ_U32(XcPKGetKeyLen(alt), 264);

    memcpy(alt, PUBKEY, sizeof(alt));
    alt[8] = 0x00; alt[9] = 0x04;        /* modulus bits */
    ASSERT_EQ_U32(XcPKGetKeyLen(alt), 264);
    return true;
}

static bool t_verify_signature(void)
{
    ASSERT_TRUE(XcVerifyPKCS1Signature((PUCHAR)SIGNATURE, (PUCHAR)PUBKEY,
                                       (PUCHAR)DIGEST));
    return true;
}

static bool t_verify_rejects_wrong_digest(void)
{
    UCHAR bad[20];

    memcpy(bad, DIGEST, sizeof(bad));
    bad[0] ^= 0xff;
    if (XcVerifyPKCS1Signature((PUCHAR)SIGNATURE, (PUCHAR)PUBKEY, bad))
        FAIL_AND_RETURN("a corrupted digest verified");

    memcpy(bad, DIGEST, sizeof(bad));
    bad[19] ^= 0x01;
    if (XcVerifyPKCS1Signature((PUCHAR)SIGNATURE, (PUCHAR)PUBKEY, bad))
        FAIL_AND_RETURN("a corrupted digest verified");
    return true;
}

static bool t_verify_rejects_wrong_signature(void)
{
    static UCHAR bad[MODULUS_BYTES];

    memcpy(bad, SIGNATURE, sizeof(bad));
    bad[0] ^= 0xff;
    if (XcVerifyPKCS1Signature(bad, (PUCHAR)PUBKEY, (PUCHAR)DIGEST))
        FAIL_AND_RETURN("a corrupted signature verified");

    memcpy(bad, SIGNATURE, sizeof(bad));
    bad[MODULUS_BYTES - 1] ^= 0x80;
    if (XcVerifyPKCS1Signature(bad, (PUCHAR)PUBKEY, (PUCHAR)DIGEST))
        FAIL_AND_RETURN("a corrupted signature verified");
    return true;
}

static bool t_verify_smaller_key(void)
{
    /* The modulus size comes out of the blob, so a shorter key works the
     * same way. */
    ASSERT_TRUE(XcVerifyPKCS1Signature((PUCHAR)SIGNATURE_1K,
                                       (PUCHAR)PUBKEY_1K, (PUCHAR)DIGEST));

    /* ...and the two keys' signatures do not cross over. */
    if (XcVerifyPKCS1Signature((PUCHAR)SIGNATURE_1K, (PUCHAR)PUBKEY,
                               (PUCHAR)DIGEST))
        FAIL_AND_RETURN("a signature from another key verified");
    return true;
}


