/*
 * XcPKDecPrivate: the private half of the console's RSA pair.
 *
 * The private blob repeats the public header under its own "RSA2" magic
 * and carries the CRT parameters after the modulus.  Every number sits
 * in a field eight bytes wider than the value the header describes, the
 * halves taking four each, so the fields stride by the blob-length field
 * and not by the modulus' width.
 *
 * The operation itself is the CRT one, which is directly visible from
 * the outside: the modulus and the private exponent can both be zeroed
 * without changing the answer, and a zeroed prime is refused.  The
 * vectors below are a throwaway 1024-bit key generated off-console,
 * stored least significant byte first the way the console reads them.
 */

