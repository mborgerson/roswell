#define MOD_BYTES  128
#define HALF       64
#define FIELD      (MOD_BYTES + 8)      /* the blob's field stride */
#define HFIELD     (FIELD / 2)
#define OFF_MOD    0x14
#define OFF_P      (OFF_MOD + FIELD)
#define OFF_Q      (OFF_P + HFIELD)
#define OFF_DP     (OFF_Q + HFIELD)
#define OFF_DQ     (OFF_DP + HFIELD)
#define OFF_QI     (OFF_DQ + HFIELD)
#define OFF_D      (OFF_QI + HFIELD)
#define BLOB_BYTES (OFF_D + FIELD)

#define RSA1_MAGIC 0x31415352
#define RSA2_MAGIC 0x32415352
#define GUARD      0xAA

static UCHAR g_priv[BLOB_BYTES + 64];
static UCHAR g_pub[OFF_MOD + FIELD];
static UCHAR g_in[MOD_BYTES + 64];
static UCHAR g_out[MOD_BYTES + 64];

static void header(PUCHAR blob, ULONG magic)
{
    ((ULONG *)blob)[0] = magic;
    ((ULONG *)blob)[1] = MOD_BYTES + 8;
    ((ULONG *)blob)[2] = MOD_BYTES * 8;
    ((ULONG *)blob)[3] = MOD_BYTES - 1;
    ((ULONG *)blob)[4] = 65537;
}

static void build_private(void)
{
    memset(g_priv, 0, sizeof(g_priv));
    header(g_priv, RSA2_MAGIC);
    memcpy(g_priv + OFF_MOD, MODULUS, MOD_BYTES);
    memcpy(g_priv + OFF_P, PRIME1, HALF);
    memcpy(g_priv + OFF_Q, PRIME2, HALF);
    memcpy(g_priv + OFF_DP, EXPONENT1, HALF);
    memcpy(g_priv + OFF_DQ, EXPONENT2, HALF);
    memcpy(g_priv + OFF_QI, COEFFICIENT, HALF);
    memcpy(g_priv + OFF_D, PRIVEXP, MOD_BYTES);
}

static void build_public(void)
{
    memset(g_pub, 0, sizeof(g_pub));
    header(g_pub, RSA1_MAGIC);
    memcpy(g_pub + OFF_MOD, MODULUS, MOD_BYTES);
}

static void set_value(const UCHAR *value)
{
    memset(g_in, 0, sizeof(g_in));
    if (value != NULL)
        memcpy(g_in, value, MOD_BYTES);
    memset(g_out, GUARD, sizeof(g_out));
}

static bool untouched(void)
{
    unsigned i;

    for (i = 0; i < sizeof(g_out); i++)
        if (g_out[i] != GUARD)
            return false;
    return true;
}

/* The private operation gives back what the public one turned the
 * message into. */
static bool t_decrypts_the_public_operation(void)
{
    build_public();
    set_value(PLAIN);
    ASSERT_EQ_U32(XcPKEncPublic(g_pub, g_in, g_out), 1);
    ASSERT_TRUE(memcmp(g_out, CIPHER, MOD_BYTES) == 0);

    build_private();
    set_value(CIPHER);
    ASSERT_EQ_U32(XcPKDecPrivate(g_priv, g_in, g_out), 1);
    ASSERT_TRUE(memcmp(g_out, PLAIN, MOD_BYTES) == 0);
    return true;
}

/* The answer is the modulus' width, with the eight bytes above it
 * zeroed and nothing written past them. */
static bool t_the_answer_carries_eight_zero_bytes(void)
{
    unsigned i;

    build_private();
    set_value(CIPHER);
    ASSERT_EQ_U32(XcPKDecPrivate(g_priv, g_in, g_out), 1);
    for (i = MOD_BYTES; i < MOD_BYTES + 8; i++)
        ASSERT_EQ_U32(g_out[i], 0);
    for (i = MOD_BYTES + 8; i < sizeof(g_out); i++)
        ASSERT_EQ_U32(g_out[i], GUARD);
    return true;
}

/* The operation runs on the CRT parameters alone: neither the modulus
 * nor the private exponent is read. */
static bool t_the_modulus_and_private_exponent_are_not_read(void)
{
    build_private();
    memset(g_priv + OFF_MOD, 0, FIELD);
    memset(g_priv + OFF_D, 0, FIELD);
    set_value(CIPHER);
    ASSERT_EQ_U32(XcPKDecPrivate(g_priv, g_in, g_out), 1);
    ASSERT_TRUE(memcmp(g_out, PLAIN, MOD_BYTES) == 0);
    return true;
}

/* A prime with nothing in it is refused before anything is written. */
static bool t_a_zero_prime_is_refused(void)
{
    build_private();
    memset(g_priv + OFF_P, 0, HFIELD);
    set_value(CIPHER);
    ASSERT_EQ_U32(XcPKDecPrivate(g_priv, g_in, g_out), 0);
    ASSERT_TRUE(untouched());

    build_private();
    memset(g_priv + OFF_Q, 0, HFIELD);
    set_value(CIPHER);
    ASSERT_EQ_U32(XcPKDecPrivate(g_priv, g_in, g_out), 0);
    ASSERT_TRUE(untouched());
    return true;
}

/* The two primes have distinct roles -- the first one is the one the
 * coefficient inverts against -- so exchanging them answers, but not
 * with the message. */
static bool t_the_primes_are_not_interchangeable(void)
{
    build_private();
    memcpy(g_priv + OFF_P, PRIME2, HALF);
    memcpy(g_priv + OFF_Q, PRIME1, HALF);
    set_value(CIPHER);
    ASSERT_EQ_U32(XcPKDecPrivate(g_priv, g_in, g_out), 1);
    ASSERT_TRUE(memcmp(g_out, PLAIN, MOD_BYTES) != 0);
    return true;
}

/* Only the private magic is accepted; the public blob's is not. */
static bool t_only_the_private_magic_is_accepted(void)
{
    build_private();
    header(g_priv, RSA1_MAGIC);
    set_value(CIPHER);
    ASSERT_EQ_U32(XcPKDecPrivate(g_priv, g_in, g_out), 0);
    ASSERT_TRUE(untouched());

    build_private();
    header(g_priv, 0);
    set_value(CIPHER);
    ASSERT_EQ_U32(XcPKDecPrivate(g_priv, g_in, g_out), 0);
    ASSERT_TRUE(untouched());
    return true;
}

/* The value is not checked against the modulus: handing over the
 * modulus itself is zero in both halves, and comes back as zero. */
static bool t_the_value_is_not_range_checked(void)
{
    unsigned i;

    build_private();
    set_value(MODULUS);
    ASSERT_EQ_U32(XcPKDecPrivate(g_priv, g_in, g_out), 1);
    for (i = 0; i < MOD_BYTES; i++)
        ASSERT_EQ_U32(g_out[i], 0);
    return true;
}

/* The value handed in is one word wider than the modulus.  That word is
 * part of the number -- setting it answers something else, where the
 * public operation refuses outright -- and the four bytes above it are
 * not read at all. */
static bool t_the_value_is_one_word_wider(void)
{
    build_private();
    set_value(CIPHER);
    memset(g_in + MOD_BYTES + 4, 0xFF, 4);
    ASSERT_EQ_U32(XcPKDecPrivate(g_priv, g_in, g_out), 1);
    ASSERT_TRUE(memcmp(g_out, PLAIN, MOD_BYTES) == 0);

    build_private();
    set_value(CIPHER);
    g_in[MOD_BYTES] = 1;
    ASSERT_EQ_U32(XcPKDecPrivate(g_priv, g_in, g_out), 1);
    ASSERT_TRUE(memcmp(g_out, PLAIN, MOD_BYTES) != 0);
    return true;
}

